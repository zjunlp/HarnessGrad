"""Build a fresh ALFWorld/TextWorld environment for one game file, and replay actions.

Why this file exists, and why it is shared
------------------------------------------
ALFWorld is interactive and multi-turn, which the platform's one-shot task contract
does not express. The platform's answer to that is the tau-bench shape: the agent acts
through a CLI, the CLI writes a log, and the check **replays the log in a fresh
environment** and reads the environment's own verdict. For that to mean anything, the
CLI and the check have to agree *exactly* on how an action becomes an observation --
otherwise the trajectory the agent saw is not the trajectory the check scores, and the
disagreement shows up as an inexplicable 0.

So there is exactly one implementation of "build the environment, reset it, apply an
action", and both programs import it:

    data/datasets/alfworld/lib/gym_env.py   <- this file
    data/datasets/alfworld/cli/alf          <- the agent's command line, imports this
    data/datasets/alfworld/verify/check.py  <- the grade, imports this

The adapter copies this file into the task workdir for the CLI via `SETUP`, and copies
it there **again** at verification time via `VERIFY.inputs`. The second copy is what
makes the check trustworthy: the agent may edit anything in its workdir, including
this file, and the edit does not survive into the check.

What "the environment's own won flag" means here
-----------------------------------------------
`won` is computed by TextWorld from the game's PDDL goal. It is not produced by
ALFWorld, not by this file, and not by the agent. Nothing in the platform's own code
decides success: `infos["won"]` is the benchmark's verdict, and the check reads it.

The step budget
---------------
`STEP_BUDGET` is the number of `env.step` calls an episode may use. It is declared once
and used by the CLI (which refuses action 51) and by the check (which replays at most
50) and by TextWorld itself (`max_episode_steps`, which ends the episode when the
budget runs out). The three have to be the same number or a trajectory could be
legal for the agent and truncated for the check.
"""
from __future__ import annotations

#: Upstream ALFWorld `configs/eval_config.yaml:133` sets
#: `max_nb_steps_per_episode: 50`, matching the paper's 50-step episode limit.
#: Declared here once for the CLI, replay and TextWorld -- see the module docstring.
STEP_BUDGET = 50

#: The file TextWorld loads. Generated by ALFWorld's own tooling and shipped in the
#: `0.4.2` release asset; it embeds the PDDL domain, the task-specific grammar and the
#: problem, so a game file is self-contained and does not need `$ALFWORLD_DATA/logic`.
GAME_FILENAME = "game.tw-pddl"

#: The agent's action log, one JSON object per line. It is the *only* thing the check
#: reads from the agent: the check never trusts an observation, a `won` flag or a
#: summary that the CLI wrote, because all of those can be forged by the agent that
#: wrote them. Actions are safe to trust in a way that verdicts are not -- replaying
#: them in a fresh environment is what turns them into a verdict.
LOG_FILENAME = "alf_actions.jsonl"


def build(game_path: str, budget: int = STEP_BUDGET):
    """A fresh, single-game TextWorld environment.

    `AlfredDemangler(shuffle=False)` is not decoration: the game file's actions use
    ALFRED's demangled object names (`desk 2`, `alarmclock 1`) and TextWorld's raw names
    are the mangled ones, so without the demangler every command is "not admissible".
    `shuffle=False` because the benchmark's evaluation is not randomised and a shuffled
    world would make two replays of one log disagree.
    """
    import textworld
    import textworld.gym
    from alfworld.agents.environment.alfred_tw_env import AlfredDemangler, AlfredInfos

    request_infos = textworld.EnvInfos(won=True, admissible_commands=True,
                                       extras=["gamefile"])
    env_id = textworld.gym.register_games(
        [str(game_path)], request_infos,
        batch_size=1,
        asynchronous=False,
        max_episode_steps=budget,
        wrappers=[AlfredDemangler(shuffle=False), AlfredInfos],
    )
    return textworld.gym.make(env_id)


def reset(env) -> dict:
    """The episode's first observation. `won` is read but is always false here."""
    obs, infos = env.reset()
    return {
        "observation": obs[0],
        "admissible": list(infos.get("admissible_commands", [[]])[0]),
        "won": bool(infos.get("won", [False])[0]),
    }


def step(env, command: str) -> dict:
    """Apply one command and return what TextWorld said, including its `won` flag."""
    obs, _scores, dones, infos = env.step([command])
    return {
        "observation": obs[0],
        "admissible": list(infos.get("admissible_commands", [[]])[0]),
        "won": bool(infos.get("won", [False])[0]),
        "done": bool(dones[0]),
    }


def replay(game_path: str, actions: list[str], budget: int = STEP_BUDGET) -> dict:
    """Replay `actions` from a fresh episode and report the environment's own verdict.

    Returns the initial observation, one record per action actually applied, and
    `won` -- true when TextWorld reported the goal satisfied at **any** step. "At any
    step" is upstream's rule, not a convenience: ALFWorld's own evaluator takes the
    maximum of the per-step `won` (`alfworld/agents/eval/evaluate_dagger.py`), and an
    episode that wins and then keeps acting is still a win.

    The replay stops early when TextWorld says `done` (a win, or the budget running
    out), which is what the official evaluator does too.
    """
    env = build(game_path, budget)
    try:
        first = reset(env)
        records: list[dict] = []
        won = first["won"]
        for action in list(actions)[:budget]:
            record = dict(step(env, action))
            record["action"] = action
            records.append(record)
            won = won or record["won"]
            if record["done"]:
                break
        return {"initial_observation": first["observation"],
                "initial_admissible": first["admissible"],
                "records": records, "won": won}
    finally:
        try:
            env.close()
        except Exception:  # noqa: BLE001 - a closed env is not a measurement failure
            pass


def action_log_records(path) -> list[dict]:
    """Parse an action log defensively. A line this cannot read is not an action.

    Kept here rather than in the check so the CLI and the check read the log the same
    way. A malformed line is dropped rather than raising: the log is the agent's file,
    and a truncated write must not turn into a check that cannot run at all -- it turns
    into a shorter episode, which the check then scores honestly.
    """
    import json
    from pathlib import Path

    p = Path(path)
    if not p.is_file():
        return []
    out = []
    for line in p.read_text(errors="replace").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            record = json.loads(line)
        except ValueError:
            continue
        if isinstance(record, dict):
            out.append(record)
    return out
