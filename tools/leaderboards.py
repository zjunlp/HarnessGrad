#!/usr/bin/env python3
"""Render the four contribution boards into the README, and check that it says what we hold.

Why this is generated rather than written
----------------------------------------
A board in a README is a claim about who contributed what, and a hand-edited table is a
claim that goes stale the first time a pull request lands: the entry is added to one place
and remembered in neither. So `registry/leaderboards.json` is the record and this script
is the only thing that writes the table. `--check` fails when the README and the record
disagree, which is what makes "add yourself" a two-file change a reviewer can verify.

Four boards, because they answer four different questions
---------------------------------------------------------
`harness`, `method` and `benchmark` answer "what can this platform run, and who do I ask
about it" -- each row names a contributor, so a question about one entry has an @handle
rather than a mailing list. `results` answers "what has been measured", and it is the only
board with an admission rule: an entry needs a benchmark+metric group, a receipt in this
repository, and the tree hash the score was measured on. A score without those is not a
result, it is an anecdote.

Ranking
-------
The three support boards rank by `adoption` -- the number of independent reproductions
reported in the pull request that added the entry -- and break ties by name, so the order
is a declared number rather than an impression. The results board ranks by score inside
one (benchmark, metric) group and never across groups: a BBEH accuracy and a Terminal-Bench
pass rate are not the same axis, and a table that puts them in one column invents a
comparison.

Top ten here, complete board on the site
----------------------------------------
The README carries ten rows per board. The full board, with every entry, lives on
`HarnessGrad-Hub`; the link is part of the generated block so the two cannot drift apart
silently.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RECORD = ROOT / "registry" / "leaderboards.json"
README = ROOT / "README.md"

BEGIN = "<!-- BEGIN boards (generated by tools/leaderboards.py --write) -->"
END = "<!-- END boards -->"
TOP = 10
SITE = "https://zjunlp.github.io/HarnessGrad-Hub/leaderboards/"

HANDLE = re.compile(r"^[A-Za-z0-9](?:[A-Za-z0-9-]{0,38})$")
SHA = re.compile(r"^[0-9a-f]{40}$")

#: Which file a board's row must point at. A board entry that names nothing in the tree is
#: a name we cannot run, so it is refused rather than rendered.
REQUIRED = {
    "harness": ("path", lambda path: (ROOT / path).is_dir()),
    "method": ("preset", lambda path: (ROOT / path).is_file()),
    "benchmark": ("adapter", lambda path: (ROOT / path).is_file()),
}


def load() -> dict:
    return json.loads(RECORD.read_text(encoding="utf-8"))


def problems(record: dict) -> list[str]:
    """Every reason the record cannot be rendered, as sentences a contributor can act on."""
    found: list[str] = []
    boards = record.get("boards") or {}
    for board, (field, exists) in REQUIRED.items():
        entries = boards.get(board) or []
        if not entries:
            found.append(f"{board}: no entries")
            continue
        seen: set[str] = set()
        for entry in entries:
            name = entry.get("name", "")
            if not name:
                found.append(f"{board}: an entry has no name")
                continue
            if name in seen:
                found.append(f"{board}: {name} is listed twice")
            seen.add(name)
            path = entry.get(field, "")
            if not path:
                found.append(f"{board}/{name}: no {field}")
            elif not exists(path):
                found.append(f"{board}/{name}: {field} does not exist: {path}")
            handle = entry.get("contributor", "")
            if not HANDLE.match(handle):
                found.append(f"{board}/{name}: contributor is not a GitHub handle: {handle!r}")
            adoption = entry.get("adoption")
            if not isinstance(adoption, int) or adoption < 1:
                found.append(f"{board}/{name}: adoption must be an integer >= 1")
            if not entry.get("since"):
                found.append(f"{board}/{name}: no since date")

    group: dict[tuple[str, str], list[str]] = {}
    for entry in (record.get("results") or {}).get("entries") or []:
        name = entry.get("method") or entry.get("name") or "?"
        for field in ("benchmark", "metric", "receipt", "harness_sha", "contributor"):
            if not entry.get(field):
                found.append(f"results/{name}: no {field}")
        receipt = entry.get("receipt")
        if receipt and not (ROOT / receipt).is_file():
            found.append(f"results/{name}: receipt does not exist: {receipt}")
        sha = entry.get("harness_sha")
        if sha and not SHA.match(str(sha)):
            found.append(f"results/{name}: harness_sha is not a 40-hex tree/commit id: {sha}")
        handle = entry.get("contributor", "")
        if handle and not HANDLE.match(handle):
            found.append(f"results/{name}: contributor is not a GitHub handle: {handle!r}")
        if not isinstance(entry.get("score"), (int, float)):
            found.append(f"results/{name}: score must be a number")
        key = (str(entry.get("benchmark")), str(entry.get("metric")))
        group.setdefault(key, []).append(name)
    for (benchmark, metric), names in group.items():
        if len(names) > 1 and len(set(names)) != len(names):
            found.append(f"results/{benchmark}·{metric}: a method appears twice")
    return found


def _rows(board: str, entries: list[dict]) -> list[str]:
    ordered = sorted(entries, key=lambda e: (-int(e.get("adoption", 1)), e.get("name", "")))
    rows = [f"| # | {'harness' if board == 'harness' else board} | contributor | since | adopted | what it is |",
            "| --- | --- | --- | --- | --- | --- |"]
    for rank, entry in enumerate(ordered[:TOP], start=1):
        handle = entry["contributor"]
        rows.append(
            f"| {rank} | `{entry['name']}` | [@{handle}](https://github.com/{handle}) | "
            f"{entry['since']} | {entry['adoption']} | {entry.get('note', '')} |")
    if len(ordered) > TOP:
        rows.append("")
        rows.append(f"*{len(ordered) - TOP} more on the "
                    f"[full board]({SITE}) — top ten only here.*")
    return rows


def _result_rows(entries: list[dict]) -> list[str]:
    if not entries:
        return ["*No comparable result has been contributed yet. The admission rule is in "
                "[docs/leaderboards.md](docs/leaderboards.md): a benchmark+metric group, a "
                "receipt in this repository, and the tree hash the score was measured on.*"]
    groups: dict[tuple[str, str], list[dict]] = {}
    for entry in entries:
        groups.setdefault((entry["benchmark"], entry["metric"]), []).append(entry)
    rows: list[str] = []
    for (benchmark, metric), members in sorted(groups.items()):
        rows.append(f"**{benchmark} · {metric}**")
        rows.append("")
        rows.append("| # | score | method | harness | contributor | receipt |")
        rows.append("| --- | --- | --- | --- | --- | --- |")
        members.sort(key=lambda e: -float(e["score"]))
        for rank, entry in enumerate(members[:TOP], start=1):
            handle = entry["contributor"]
            rows.append(
                f"| {rank} | {entry['score']} | `{entry.get('method', '?')}` | "
                f"`{entry.get('harness', '?')}` | "
                f"[@{handle}](https://github.com/{handle}) | "
                f"[receipt]({entry['receipt']}) |")
        rows.append("")
    return rows


def render(record: dict) -> str:
    lines = [
        BEGIN,
        "<!-- Four boards, one record: registry/leaderboards.json. "
        "Add yourself by adding a row there and running tools/leaderboards.py --write. -->",
        "",
        "Ranked by independent reproductions reported in the pull request that added the "
        "entry, ties by name. A row's contributor is the person to @ in an issue.",
        "",
    ]
    for board, title in (("harness", "Harnesses"),
                         ("method", "RSI methods"),
                         ("benchmark", "Benchmarks")):
        lines.append(f"### {title}")
        lines.append("")
        lines.extend(_rows(board, record["boards"][board]))
        lines.append("")
    lines.append("### Measured results")
    lines.append("")
    lines.extend(_result_rows((record.get("results") or {}).get("entries") or []))
    lines.append("")
    lines.append(f"[Full boards]({SITE}) keep every entry; this table keeps the top ten.")
    lines.append(END)
    return "\n".join(lines)


def current_block(text: str) -> str | None:
    if BEGIN not in text or END not in text:
        return None
    start = text.index(BEGIN)
    stop = text.index(END) + len(END)
    return text[start:stop]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true", help="rewrite the README block")
    parser.add_argument("--check", action="store_true", help="fail if the README is stale")
    args = parser.parse_args()
    if not (args.write or args.check):
        parser.error("one of --write or --check is required")

    record = load()
    found = problems(record)
    if found:
        for line in found:
            print(f"error: {line}", file=sys.stderr)
        return 2

    rendered = render(record)
    text = README.read_text(encoding="utf-8")
    existing = current_block(text)
    if args.check:
        if existing is None:
            print("error: README has no generated board block", file=sys.stderr)
            return 1
        if existing != rendered:
            print("error: README boards are stale; run tools/leaderboards.py --write",
                  file=sys.stderr)
            return 1
        print(f"boards ok: {len(record['boards']['harness'])} harnesses, "
              f"{len(record['boards']['method'])} methods, "
              f"{len(record['boards']['benchmark'])} benchmarks, "
              f"{len((record.get('results') or {}).get('entries') or [])} results")
        return 0

    if existing is None:
        print("error: README has no generated board block to replace", file=sys.stderr)
        return 1
    README.write_text(text.replace(existing, rendered), encoding="utf-8")
    print("wrote the board block")
    return 0


if __name__ == "__main__":
    sys.exit(main())
