#!/usr/bin/env python3
"""Render the contribution boards, the benchmark catalogue, and who contributed what.

Why this is generated rather than written
-----------------------------------------
A board in a README is a claim about who contributed what, and a hand-edited table is a claim
that goes stale the first time a pull request lands. So `registry/leaderboards.json` is the
record, this script is the only writer of the tables, and `--check` fails when they disagree.

What the boards rank
--------------------
Contributors, not entries. A board that lists one row per harness with the same org on every
row ranks nothing: the reader cannot see what is being compared, and a count of 1 next to every
name is not a ranking. Each board therefore groups its entries by contributor and ranks by
**how many entries that contributor has on that board**, which is the number we can defend: it
is countable, it is in the record, and it is what "adopted" means here. The README shows the
count and a link; the details page (`docs/leaderboard-details.md`, also generated) names the
entries, so a count of eight is one click from being checkable.

The results board is the exception and stays per entry: a result belongs to a (benchmark,
metric) group, is ranked inside it by score, and needs a receipt, a tree hash and a metric. It
is not an adoption count and must not be mixed with one.

The catalogue
-------------
The benchmark board is a ranking; the catalogue is an inventory. Every declared adapter is
listed there by name, with the refused ones marked, so "59 declared" is a number a reader can
count instead of trust.

Top ten in the README, everything in the details page and on the site.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RECORD = ROOT / "registry" / "leaderboards.json"
BLOCKERS = ROOT / "registry" / "dataset-blockers.json"
README = ROOT / "README.md"
DETAILS = ROOT / "docs" / "leaderboard-details.md"

BEGIN = "<!-- BEGIN boards (generated by tools/leaderboards.py --write) -->"
END = "<!-- END boards -->"
TOP = 10
SITE = "https://zjunlp.github.io/HarnessGrad-Hub/leaderboards/"
DETAILS_LINK = "docs/leaderboard-details.md"

HANDLE = re.compile(r"^[A-Za-z0-9](?:[A-Za-z0-9-]{0,38})$")
SHA = re.compile(r"^[0-9a-f]{40}$")

REQUIRED = {
    "harness": ("path", lambda path: (ROOT / path).is_dir()),
    "method": ("preset", lambda path: (ROOT / path).is_file()),
    "benchmark": ("adapter", lambda path: (ROOT / path).is_file()),
}

BOARD_TITLES = {
    "harness": "Harnesses",
    "method": "RSI methods",
    "benchmark": "Benchmarks",
}


# ------------------------------------------------------------------ the record ---

def declared_benchmarks() -> list[str]:
    """Every adapter file: what the repository declares, not what this machine can import."""
    return sorted(path.stem for path in (ROOT / "data" / "datasets").glob("*.py")
                  if path.stem != "__init__")


def refused_benchmarks() -> set[str]:
    blockers = json.loads(BLOCKERS.read_text(encoding="utf-8"))
    refused = set()
    for entry in blockers["datasets"]:
        families = {item.get("family") for item in entry.get("blockers") or []}
        if "contract-refusal" in families:
            refused.add(entry["dataset"])
    return refused


def load() -> dict:
    return json.loads(RECORD.read_text(encoding="utf-8"))


def problems(record: dict) -> list[str]:
    """Every reason the record cannot be rendered, as sentences a contributor can act on."""
    found: list[str] = []
    boards = record.get("boards") or {}
    for board, (field, exists) in REQUIRED.items():
        entries = boards.get(board) or []
        if not entries:
            found.append(f"{board}: no entries")
            continue
        seen: set[str] = set()
        for entry in entries:
            name = entry.get("name", "")
            if not name:
                found.append(f"{board}: an entry has no name")
                continue
            if name in seen:
                found.append(f"{board}: {name} is listed twice")
            seen.add(name)
            path = entry.get(field, "")
            if not path:
                found.append(f"{board}/{name}: no {field}")
            elif not exists(path):
                found.append(f"{board}/{name}: {field} does not exist: {path}")
            handle = entry.get("contributor", "")
            if not HANDLE.match(handle):
                found.append(f"{board}/{name}: contributor is not a GitHub handle: {handle!r}")
            adoption = entry.get("adoption")
            if not isinstance(adoption, int) or adoption < 1:
                found.append(f"{board}/{name}: adoption must be an integer >= 1")
            if not entry.get("since"):
                found.append(f"{board}/{name}: no since date")
            contact = entry.get("contact")
            if contact is not None and (not isinstance(contact, str) or not contact.strip()):
                found.append(f"{board}/{name}: contact must be a nonempty string when present")

    unknown = sorted({entry["name"] for entry in boards.get("benchmark") or []}
                     - set(declared_benchmarks()))
    if unknown:
        found.append(f"benchmark: not a declared adapter: {unknown}")

    seen_results: set[tuple] = set()
    for entry in (record.get("results") or {}).get("entries") or []:
        name = entry.get("method") or entry.get("name") or "?"
        for field in ("benchmark", "metric", "receipt", "harness_sha", "contributor"):
            if not entry.get(field):
                found.append(f"results/{name}: no {field}")
        receipt = entry.get("receipt")
        if receipt and not (ROOT / receipt).is_file():
            found.append(f"results/{name}: receipt does not exist: {receipt}")
        sha = entry.get("harness_sha")
        if sha and not SHA.match(str(sha)):
            found.append(f"results/{name}: harness_sha is not a 40-hex id: {sha}")
        handle = entry.get("contributor", "")
        if handle and not HANDLE.match(handle):
            found.append(f"results/{name}: contributor is not a GitHub handle: {handle!r}")
        contact = entry.get("contact")
        if contact is not None and (not isinstance(contact, str) or not contact.strip()):
            found.append(f"results/{name}: contact must be a nonempty string when present")
        if not isinstance(entry.get("score"), (int, float)):
            found.append(f"results/{name}: score must be a number")
        key = (entry.get("benchmark"), entry.get("metric"), entry.get("method"),
               entry.get("harness"))
        if key in seen_results:
            found.append(f"results/{name}: the same method+harness appears twice in one group")
        seen_results.add(key)
    return found


# ------------------------------------------------------------------ rendering ---

def contributors(board_entries: list[dict]) -> list[tuple[str, list[dict]]]:
    """Entries grouped by contributor, most entries first, ties by handle."""
    grouped: dict[str, list[dict]] = {}
    for entry in board_entries:
        grouped.setdefault(entry["contributor"], []).append(entry)
    return sorted(grouped.items(), key=lambda item: (-len(item[1]), item[0].lower()))


def _anchor(board: str, handle: str) -> str:
    return f"{DETAILS_LINK}#{board}-{handle.lower()}"


def render(record: dict) -> str:
    lines = [
        BEGIN,
        "",
        "Ranked by **how many entries a contributor has on the board**, ties by handle. The "
        f"count links to the [details page]({DETAILS_LINK}), which names every entry, and the "
        f"[full boards]({SITE}) carry the same record with contact details.",
        "",
    ]
    for board, title in BOARD_TITLES.items():
        lines.extend([f"### {title}", "",
                      "| # | contributor | contributed |",
                      "| --- | --- | --- |"])
        for rank, (handle, entries) in enumerate(contributors(record["boards"][board]), start=1):
            if rank > TOP:
                break
            lines.append(f"| {rank} | [@{handle}](https://github.com/{handle}) | "
                         f"[{len(entries)}]({_anchor(board, handle)}) |")
        lines.append("")
    lines.extend(_result_rows((record.get("results") or {}).get("entries") or []))
    lines.append("")
    lines.append(f"[Full boards]({SITE}) keep every contributor; this table keeps the top {TOP}.")
    lines.append(END)
    return "\n".join(lines)


def _result_rows(entries: list[dict]) -> list[str]:
    lines = ["### Measured results", ""]
    if not entries:
        lines.append("*No comparable result has been contributed yet. The admission rule is in "
                     "[docs/leaderboards.md](docs/leaderboards.md): a benchmark+metric group, a "
                     "receipt in this repository, and the tree hash the score was measured on.*")
        return lines
    groups: dict[tuple[str, str], list[dict]] = {}
    for entry in entries:
        groups.setdefault((entry["benchmark"], entry["metric"]), []).append(entry)
    for (benchmark, metric), members in sorted(groups.items()):
        lines.extend([f"**{benchmark} · {metric}**", "",
                      "| # | score | method | harness | contributor | receipt |",
                      "| --- | --- | --- | --- | --- | --- |"])
        members.sort(key=lambda entry: -float(entry["score"]))
        for rank, entry in enumerate(members[:TOP], start=1):
            handle = entry["contributor"]
            lines.append(
                f"| {rank} | {entry['score']} | `{entry.get('method', '?')}` | "
                f"`{entry.get('harness', '?')}` | [@{handle}](https://github.com/{handle}) | "
                f"[receipt]({entry['receipt']}) |")
        lines.append("")
    return lines


def render_details(record: dict) -> str:
    """Who contributed what: the page a board's count links to."""
    lines = [
        "# Board details: who contributed what",
        "",
        "Generated by `python3 tools/leaderboards.py --write` from "
        "[`registry/leaderboards.json`](../registry/leaderboards.json); do not edit by hand. The "
        "[README](../README.md#contribution-boards) shows one row per contributor with a count, "
        "so the board stays readable and this page stays complete.",
        "",
    ]
    for board, title in BOARD_TITLES.items():
        lines.extend([f"## {title}", ""])
        for handle, entries in contributors(record["boards"][board]):
            lines.extend([f'<a id="{board}-{handle.lower()}"></a>', "",
                          f"### [@{handle}](https://github.com/{handle}) — {len(entries)} "
                          f"{'entry' if len(entries) == 1 else 'entries'}", "",
                          "| entry | since | what it is |",
                          "| --- | --- | --- |"])
            for entry in sorted(entries, key=lambda item: item["name"]):
                lines.append(f"| `{entry['name']}` | {entry['since']} | {entry.get('note', '')} |")
            lines.append("")
    lines.extend(_result_details((record.get("results") or {}).get("entries") or []))
    return "\n".join(lines)


def _result_details(entries: list[dict]) -> list[str]:
    lines = ["## Measured results", ""]
    if not entries:
        lines.append("No comparable result has been contributed yet.")
        return lines
    for entry in sorted(entries, key=lambda item: (item["benchmark"], item["metric"],
                                                   -float(item["score"]))):
        lines.append(f"- `{entry['benchmark']}` · {entry['metric']}: **{entry['score']}** — "
                     f"`{entry.get('method', '?')}` on `{entry.get('harness', '?')}`, "
                     f"@{entry['contributor']}, [receipt]({entry['receipt']}), "
                     f"tree {entry['harness_sha'][:12]}")
    return lines


def benchmark_row() -> str:
    """The benchmarks row of the README's axis table: every declared name, in one cell.

    A count is a number a reader has to trust; the list is one they can read. It is a single
    Markdown table row because it belongs in the table it describes -- a second section
    repeating the same names would be a second place to keep in step.
    """
    names = declared_benchmarks()
    refused = refused_benchmarks()
    listed = ", ".join(f"`{name}`" + (" †" if name in refused else "") for name in names)
    return (f"| **benchmarks** | {len(names)} declared, **{len(names) - len(refused)} runnable**, "
            f"{len(refused)} refused (†) — every one listed: {listed} | "
            f"`data/datasets/`, detail in [`DATASETS.md`](DATASETS.md) |")


# ---------------------------------------------------------------------- files ---

def _block(text: str, begin: str, end: str) -> str | None:
    if begin not in text or end not in text:
        return None
    return text[text.index(begin):text.index(end) + len(end)]


def _replace(text: str, begin: str, end: str, rendered: str) -> str:
    existing = _block(text, begin, end)
    if existing is None:
        raise SystemExit(f"error: the file has no block starting with {begin!r}")
    return text.replace(existing, rendered)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not (args.write or args.check):
        parser.error("one of --write or --check is required")

    record = load()
    found = problems(record)
    if found:
        for line in found:
            print(f"error: {line}", file=sys.stderr)
        return 2

    boards, details = render(record), render_details(record)
    readme = README.read_text(encoding="utf-8")
    if args.check:
        stale = []
        if _block(readme, BEGIN, END) != boards:
            stale.append("the contributor boards")
        if benchmark_row() not in readme:
            stale.append("the benchmarks row (its list of declared adapters)")
        if not DETAILS.is_file() or DETAILS.read_text(encoding="utf-8") != details:
            stale.append(DETAILS_LINK)
        if stale:
            print("stale: " + ", ".join(stale) + "; run python3 tools/leaderboards.py --write",
                  file=sys.stderr)
            return 1
        print(f"boards ok: {len(record['boards']['harness'])} harnesses, "
              f"{len(record['boards']['method'])} methods, "
              f"{len(record['boards']['benchmark'])} benchmarks, "
              f"{len((record.get('results') or {}).get('entries') or [])} results")
        return 0

    readme = _replace(readme, BEGIN, END, boards)
    if benchmark_row() not in readme:
        row = next((line for line in readme.splitlines()
                    if line.startswith("| **benchmarks** |")), None)
        if row is None:
            raise SystemExit("error: the README has no benchmarks row to update")
        readme = readme.replace(row, benchmark_row())
    README.write_text(readme, encoding="utf-8")
    DETAILS.write_text(details, encoding="utf-8")
    print(f"wrote the boards and the benchmarks row into {README.name}, and {DETAILS_LINK}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
