def _toy_files_tasks(name: str) -> list[dict]:
    """Toy tasks for the scaffold.

    The ticket must be one the initial state actually holds. The first version used
    `i + 1` over an initial state of three tickets, so most tasks asked to close a ticket
    that was not there -- closing it changed nothing, the reference state equalled the
    initial one, and the **do-nothing arm passed the state half** of the check. It still
    scored 0 (the audit was missing), which is exactly why the evidence line is worth
    reading: `state_matches=True` on a no-op is the tell.
    """
    return [{"task_id": f"{name}/task/{i}", "ticket_id": (i % 3) + 1} for i in range(16)]


