def _toy_rows(name: str) -> list[dict]:
    """A toy table sized so the hashed split has tasks on both sides for *this* name."""
    from data.scaffolds.qa.base import is_eval

    count = TOY_ROWS_MIN
    while True:
        rows = [{"question": f"What is {7 + i} + {5 + i}?",
                 "answer": str((7 + i) + (5 + i))} for i in range(count)]
        sides = {is_eval(f"{name}/test/{i}") for i in range(count)}
        if sides == {True, False}:
            return rows
        count += 1


