FILES_CHECK_TEMPLATE = Template('''#!/usr/bin/env python3
"""$name: the check. Generated by `python3 tools/new_dataset.py --kind files`.

It reads the **state** the agent left in the workdir and re-derives the grade from a gold
that the platform materializes after the harness has stopped (`VERIFY.inputs`), so the copy
read here is the platform\'s and not anything the agent could have edited.

Two outcomes that must not be confused, and this check keeps them apart:

* **the task cannot be measured** -- the gold it was handed is missing or unreadable. No
  reward file is written and the evidence says `measured: false`; `eval/verification/verifier.py` reports
  that as an unmeasured task rather than as a zero the agent earned.
* **the agent failed** -- the interface file was there and the state does not match. That is
  a `0`, written like any other reward.

Outputs: `verifier/reward.txt` (0 or 1) and `verifier/evidence.json`.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def _read_json(path: Path):
    try:
        return json.loads(path.read_text())
    except (OSError, json.JSONDecodeError):
        return None


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--workdir", default=".")
    ap.add_argument("--gold", default="gold.json")
    ap.add_argument("--state", default="state/tickets.json")
    ap.add_argument("--audit", default="state/audit.log")
    ap.add_argument("--reward-file", default="verifier/reward.txt")
    ap.add_argument("--evidence-file", default="verifier/evidence.json")
    args = ap.parse_args(argv)

    workdir = Path(args.workdir)
    reward_path = workdir / args.reward_file
    evidence_path = workdir / args.evidence_file
    reward_path.parent.mkdir(parents=True, exist_ok=True)

    def write(measured: bool, why: str, reward=None, **extra) -> int:
        evidence = {"measured": measured, "why": why, **extra}
        evidence_path.write_text(json.dumps(evidence, indent=1, ensure_ascii=False))
        if measured and reward is not None:
            reward_path.write_text(f"{reward:g}")
        print(why)
        return 0 if reward == 1 else (1 if measured else 2)

    gold = _read_json(workdir / args.gold)
    if gold is None:
        # The platform\'s own input is missing, so nothing here is the agent\'s fault.
        return write(False, f"no readable gold at {args.gold}; this cannot be measured")

    state = _read_json(workdir / args.state)
    if state is None:
        # The interface file was materialized by SETUP, so its absence is a failure to act.
        return write(True, f"{args.state} is missing or unreadable", reward=0.0,
                     state_matches=False)

    audit = workdir / args.audit
    audit_lines = [l for l in audit.read_text().splitlines() if l.strip()] \
        if audit.is_file() else []
    wanted = str(gold.get("ticket_id"))
    logged = any(wanted in line for line in audit_lines)
    matches = state == gold.get("state")
    if matches and logged:
        return write(True, f"{args.state} matches the gold and the audit names {wanted}",
                     reward=1.0, state_matches=True, audit_lines=len(audit_lines))
    return write(True,
                 f"state_matches={matches}; audit names {wanted}: {logged}",
                 reward=0.0, state_matches=matches, audit_lines=len(audit_lines))


if __name__ == "__main__":
    raise SystemExit(main())
''')


