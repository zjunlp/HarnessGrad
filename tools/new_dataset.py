COMMAND_CHECK_TEMPLATE = Template('''#!/usr/bin/env python3
"""$name: the check. Generated by `tools/new_dataset.py --kind command`.

It runs with the task workdir as its working directory, reads the artefact the agent left,
compares it with the gold `VERIFY.inputs` re-materialised, and writes the grade. The
platform's rules for a check (`docs/dataset-onboarding.md` section 3):

* everything it imports travels in `VERIFY.inputs` -- it may **not** import the platform
  tree, because the verification namespace hides it;
* it writes `reward.txt` and `evidence.json`, and exits 0;
* a check that cannot measure writes **no** reward file, says `measured: false` and why,
  and exits 3 -- "unmeasured" is not "failed";
* an empty or missing artefact is a **measured zero**: the task ran and the agent left
  nothing, which is a real result.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--answer", default="answer.txt")
    parser.add_argument("--gold", default="gold.json")
    parser.add_argument("--reward-file", default="verifier/reward.txt")
    parser.add_argument("--evidence-file", default="verifier/evidence.json")
    args = parser.parse_args()

    work = Path.cwd()
    gold = json.loads((work / args.gold).read_text(encoding="utf-8"))["answer"]
    answer_path = work / args.answer
    prediction = answer_path.read_text(encoding="utf-8").strip() if answer_path.is_file() else ""

    hit = prediction.strip().lower() == str(gold).strip().lower()
    reward = 1.0 if hit else 0.0
    _write(work / args.reward_file, f"{reward:g}\\n")
    _write(work / args.evidence_file, json.dumps({
        "measured": True,
        "official": {"metric": "case-insensitive exact match on answer.txt",
                     "label": gold},
        "reward": reward,
        "prediction": prediction[:2000],
        "why": f"{'matches' if hit else 'no match for'} {prediction!r} vs {gold!r}",
    }, indent=1, sort_keys=True) + "\\n")
    print(f"reward {reward:g}: {'matches' if hit else 'no match for'} "
          f"{prediction!r} vs {gold!r}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
''')

