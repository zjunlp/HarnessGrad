# ------------------------------------------------------------------ the record ---

def declared_benchmarks() -> list[str]:
    return sorted(path.stem for path in (ROOT / "data" / "datasets").glob("*.py")
                  if path.stem != "__init__")


def record() -> dict:
    return json.loads(RECORD.read_text(encoding="utf-8"))


def entries(record: dict) -> list[dict]:
    """Every credited entry, with its kind attached."""
    out = []
    for board in BOARDS:
        for entry in record["boards"][board]:
            out.append({**entry, "kind": board})
    for entry in record.get("platform") or []:
        out.append({**entry, "kind": "platform"})
    for entry in (record.get("results") or {}).get("entries") or []:
        out.append({"name": f"{entry['benchmark']}·{entry['metric']}", "kind": "result",
                    "contributor": entry["contributor"], "since": entry.get("since", ""),
                    "note": f"{entry.get('method', '?')} on {entry.get('harness', '?')}"})
    return out


def problems(record: dict) -> list[str]:
    found: list[str] = []
    people = {person["handle"] for person in record.get("people") or []}
    if not people:
        found.append("no people are listed")
    credited = {entry["contributor"] for entry in entries(record)}
    for handle in sorted(credited - people):
        found.append(f"a credit names @{handle}, who is not in `people`")
    for handle in sorted(people - credited):
        found.append(f"@{handle} is listed with no credit")

    for board in BOARDS:
        listed = {entry["name"] for entry in record["boards"][board]}
        if board == "benchmark":
            missing = sorted(set(declared_benchmarks()) - listed)
            if missing:
                found.append(f"benchmark: declared but not credited: {missing}")
            extra = sorted(listed - set(declared_benchmarks()))
            if extra:
                found.append(f"benchmark: credited but not declared: {extra}")
    for entry in record.get("platform") or []:
        path = ROOT / entry["path"]
        if not path.exists():
            found.append(f"platform/{entry.get('name')}: path does not exist: {entry['path']}")
    for entry in entries(record):
        if not entry.get("since", "").startswith("20"):
            found.append(f"{entry['kind']}/{entry.get('name')}: no since month")
    for person in record.get("people") or []:
        if not person.get("handle") or not person.get("name"):
            found.append("a person has no handle or no name")
    return found


# ------------------------------------------------------------------ rendering ---

def months(items: list[dict]) -> list[str]:
    values = sorted({entry["since"][:7] for entry in items if entry.get("since")})
    if not values:
        return []
    first, last = values[0], values[-1]
    year, month = (int(part) for part in first.split("-"))
    out = []
    while True:
        current = f"{year:04d}-{month:02d}"
        out.append(current)
        if current == last:
            break
        month += 1
        if month == 13:
            year, month = year + 1, 1
    return out


def totals(items: list[dict]) -> list[tuple[str, int]]:
    counts = Counter(entry["contributor"] for entry in items)
    return sorted(counts.items(), key=lambda item: (-item[1], item[0].lower()))


def _kind_counts(items: list[dict]) -> Counter:
    return Counter(entry["kind"] for entry in items)


WINDOW_DAYS = 92


def _window(record: dict) -> list[str]:
    """The last three months of days, ending at the record's own `updated` date.

    Fixed rather than data-driven: a chart whose axis ends where the data ends cannot show a
    quiet week, and a reader comparing two months needs the same window in both. Entries dated
    before the window are counted in the total but not drawn.
    """
    import datetime

    end = datetime.date.fromisoformat(record.get("updated") or "2026-11-03")
    start = end - datetime.timedelta(days=WINDOW_DAYS - 1)
    return [(start + datetime.timedelta(days=offset)).isoformat()
            for offset in range(WINDOW_DAYS)]


def avatar_data_uri(handle: str) -> str | None:
    """The cached avatar as a data URI, or None when this person has no cached image."""
    for suffix in (".png", ".jpg", ".jpeg"):
        path = AVATARS / f"{handle}{suffix}"
        if path.is_file():
            import base64
            kind = "jpeg" if suffix in (".jpg", ".jpeg") else "png"
            return f"data:image/{kind};base64," + base64.b64encode(path.read_bytes()).decode()
    return None


def _avatar(handle: str, cx: float, cy: float, radius: float, colour: str) -> str:
    """A round avatar, with the initial underneath as the fallback.

    The image is a data URI from the cache (see `AVATARS` for why not a URL). The circle and
    the initial are drawn first and stay visible if this person has no cached image, so a
    missing avatar degrades to a letter rather than to a hole.
    """
    size = radius * 2
    base = (f'<circle cx="{cx:.1f}" cy="{cy:.1f}" r="{radius:.1f}" fill="{colour}" '
            f'opacity="0.18"/>'
            f'<text x="{cx:.1f}" y="{cy + radius * 0.4:.1f}" font-size="{radius:.1f}" '
            f'text-anchor="middle" fill="{colour}">{handle[:1].upper()}</text>')
    uri = avatar_data_uri(handle)
    if uri is None:
        return f"<g>{base}</g>"
    return (f'<g>{base}<image href="{uri}" x="{cx - radius:.1f}" y="{cy - radius:.1f}" '
            f'width="{size:.1f}" height="{size:.1f}" '
            f'clip-path="circle({radius:.1f}px at {radius:.1f}px {radius:.1f}px)"/></g>')


#: Two label rows closer than this overlap once the avatar and the handle are drawn.
LABEL_GAP = 30.0


def _label_layout(rows: list[tuple[str, float, int, str]],
                  top: float, bottom: float) -> list[tuple[str, float, float, int, str]]:
    """Place right-hand labels without overlap, keeping each tied to its curve's end.

    `rows` is (handle, end-of-curve y, total, colour); the result is (handle, point y, label y,
    total, colour), top to bottom. A label is pushed down until it clears the previous one, and
    the whole stack is shifted back inside `[top, bottom]` afterwards, so a crowded panel stays
    legible instead of spilling into the footnote. The leader line drawn from a point to its
    label is what keeps a moved label honest.
    """
    ordered = sorted(rows, key=lambda row: row[1])
    placed: list[list] = []
    previous = float("-inf")
    for handle, point_y, total, colour in ordered:
        label_y = max(point_y, previous + LABEL_GAP)
        placed.append([handle, point_y, label_y, total, colour])
        previous = label_y
    overflow = placed[-1][2] - bottom
    if overflow > 0:
        for row in placed:
            row[2] -= overflow
    if placed[0][2] < top:
        delta = top - placed[0][2]
        for row in placed:
            row[2] += delta
    return [tuple(row) for row in placed]


def render_svg(record: dict, board: str) -> str:
    """One board as a growth curve: cumulative entries per contributor over time.

    A calendar says *when* something landed but reading growth out of it means counting
    squares. A cumulative line says growth directly — the shape a star-history chart has —
    and a flat segment is a true statement ("nobody added to this board for a week").
    """
    items = [entry for entry in entries(record) if entry["kind"] == board]
    people = [handle for handle, _ in totals(items)]          # a contributor with no entry
    if not people:                                            # on this board has no line
        return (f'<svg xmlns="http://www.w3.org/2000/svg" width="640" height="120">'
                f'<text x="16" y="40" font-size="12" fill="#6e7781">No entries yet.</text></svg>')
    days = _window(record)
    import datetime

    colour = KIND_COLOURS[board]
    title = {"harness": "Harnesses", "method": "RSI methods", "benchmark": "Benchmarks"}[board]
    series = {}
    for handle in people:
        running, points = 0, []
        for day in days:
            running += len([entry for entry in items
                            if entry["contributor"] == handle and entry["since"][:10] == day])
            points.append(running)
        series[handle] = points
    total = max(len([entry for entry in items if entry["contributor"] == handle])
                for handle in people) or 1

    left, top, right, bottom = 52, 58, 132, 46
    width, height = 900, 300
    plot_w, plot_h = width - left - right, height - top - bottom
    def x_of(index: int) -> float:
        return left + plot_w * (index / max(len(days) - 1, 1))
    def y_of(value: int) -> float:
        return top + plot_h * (1 - value / total)
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
             f'viewBox="0 0 {width} {height}" font-family="-apple-system,Segoe UI,Helvetica,'
             f'Arial,sans-serif" role="img" aria-label="{title} growth">',
             f'<rect width="{width}" height="{height}" fill="#ffffff"/>',
             f'<text x="16" y="28" font-size="13" font-weight="600" fill="#1f2328">{title} '
             f'— cumulative contributions</text>',
             f'<text x="16" y="44" font-size="11" fill="#6e7781">{len(items)} entries; steps are '
             f'days, so a flat segment means nothing landed</text>']
    # grid + y labels at 0, half, max
    for value in (0, total // 2, total):
        y = y_of(value)
        parts.append(f'<line x1="{left}" y1="{y:.1f}" x2="{left + plot_w}" y2="{y:.1f}" '
                     f'stroke="#e6e8eb" stroke-width="1"/>')
        parts.append(f'<text x="{left - 8}" y="{y + 4:.1f}" font-size="10" fill="#6e7781" '
                     f'text-anchor="end">{value}</text>')
    for index, day in enumerate(days):
        if day[8:10] != "01":
            continue
        parts.append(f'<text x="{x_of(index):.1f}" y="{top + plot_h + 18}" font-size="10" '
                     f'fill="#6e7781" text-anchor="middle">{day[:7]}</text>')
    # Rows are drawn first, then the right-hand labels, because two contributors whose curves
    # end close together would otherwise print on top of each other: 9 and 8 entries are two
    # pixels apart on a 300 px panel, and "crepuscular-drizzle" is wider than that.
    label_rows: list[tuple[str, float, int, str]] = []
    for rank, handle in enumerate(people):
        values = series[handle]
        points = " ".join(f"{x_of(i):.1f},{y_of(v):.1f}" for i, v in enumerate(values))
        shade = colour if len(people) == 1 else PALETTE[rank % len(PALETTE)]
        parts.append(f'<polyline points="{points}" fill="none" stroke="{shade}" '
                     f'stroke-width="2" stroke-linejoin="round"/>')
        for index, value in enumerate(values):
            if index and value == values[index - 1]:
                continue
            if not value:
                continue
            parts.append(f'<g><title>{days[index]} · @{handle} · cumulative {value} of '
                         f'{len(items)}</title><circle cx="{x_of(index):.1f}" '
                         f'cy="{y_of(value):.1f}" r="3" fill="{shade}"/></g>')
        label_rows.append((handle, y_of(values[-1]), values[-1], shade))
    # Labels are laid out top to bottom with a minimum gap; a label that had to move keeps a
    # leader line back to its curve's end, so the association is never guessed.
    placed = _label_layout(label_rows, top + 10, height - 44)
    label_x = left + plot_w + 14
    for handle, point_y, label_y, total, shade in placed:
        parts.append(f'<line x1="{left + plot_w + 2}" y1="{point_y:.1f}" '
                     f'x2="{label_x + 2}" y2="{label_y:.1f}" stroke="{shade}" '
                     f'stroke-width="1" opacity="0.5"/>')
        parts.append(_avatar(handle, label_x + 8, label_y - 3, 8, shade))
        parts.append(f'<text x="{label_x + 20}" y="{label_y + 4:.1f}" font-size="11" '
                     f'fill="#1f2328">{handle}</text>')
        parts.append(f'<text x="{label_x + 20}" y="{label_y + 17:.1f}" font-size="10" '
                     f'fill="#6e7781">{total} entries</text>')
    parts.append(f'<text x="16" y="{height - 8}" font-size="10" fill="#6e7781">'
                 f'{days[0]} to {days[-1]}; the date is when an entry was adopted into the '
                 f'record. The website has a draggable window.</text>')
    parts.append("</svg>")
    return "\n".join(parts)


