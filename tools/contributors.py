#!/usr/bin/env python3
"""Draw who contributed what, and when -- a contribution graph, not a leaderboard.

Why a graph instead of a ranking
--------------------------------
A table with three rows says "someone has 87 and someone has 2", which is a scoreboard. It
does not say *what* the second person did, and it invites reading the first row as quality.
The graph keeps the same record but answers the question a reader actually has: this person
contributed these benchmarks, this method, this piece of the platform, in this month. Hovering
a cell says which ones.

Layout
------
* **x** -- time, by month, from the earliest recorded `since` to the latest.
* **y** -- contributors, ordered by total entries so the eye starts at the densest row; the
  right-hand column repeats the total *and* the rank, so the ordering is stated rather than
  implied by position.
* **cell** -- one square per (contributor, month), coloured by the kind of work and labelled
  with its ``<title>``: the native tooltip lists the entries. That is the whole interaction;
  nothing here needs JavaScript, which matters because GitHub strips it from Markdown.
* **legend** -- one swatch per kind, so a colour never has to be guessed.

The website carries the same record with a date-range picker; this file is the static drawing.
`docs/contributors.md` lists every entry per person for anyone who would rather read than hover.

What is derived and what is declared
------------------------------------
`registry/leaderboards.json` is the record: one entry per harness, method, benchmark, platform
piece and measured result, each with a `contributor` and a `since` month. This script derives
the graph from it and refuses a record that names an unknown person, an artefact that does not
exist, or a declared adapter with no credit. `since` is the month the entry was adopted into
the catalogue, not a claim about when the file was first written: the history was squashed for
release, so the honest date available is the record's.
"""
