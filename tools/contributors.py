#!/usr/bin/env python3
"""Draw who contributed what, and when -- a contribution graph, not a leaderboard.

Why a graph instead of a ranking
--------------------------------
A table with three rows says "someone has 87 and someone has 2", which is a scoreboard. It
does not say *what* the second person did, and it invites reading the first row as quality.
The graph keeps the same record but answers the question a reader actually has: this person
contributed these benchmarks, this method, this piece of the platform, in this month. Hovering
a cell says which ones.

Layout
------
* **x** -- time, by month, from the earliest recorded `since` to the latest.
* **y** -- contributors, ordered by total entries so the eye starts at the densest row; the
  right-hand column repeats the total *and* the rank, so the ordering is stated rather than
  implied by position.
* **cell** -- one square per (contributor, month), coloured by the kind of work and labelled
  with its ``<title>``: the native tooltip lists the entries. That is the whole interaction;
  nothing here needs JavaScript, which matters because GitHub strips it from a README.
* **legend** -- one swatch per kind, so a colour never has to be guessed.

The website carries the same record with a date-range picker; this file is the static drawing.
`docs/contributors.md` lists every entry per person for anyone who would rather read than hover.

What is derived and what is declared
------------------------------------
`registry/leaderboards.json` is the record: one entry per harness, method, benchmark, platform
piece and measured result, each with a `contributor` and a `since` month. This script derives
the graph from it and refuses a record that names an unknown person, an artefact that does not
exist, or a declared adapter with no credit. `since` is the month the entry was adopted into
the catalogue, not a claim about when the file was first written: the history was squashed for
release, so the honest date available is the record's.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RECORD = ROOT / "registry" / "leaderboards.json"
README = ROOT / "README.md"
DETAILS = ROOT / "docs" / "contributors.md"
FIGURE = ROOT / ".github" / "assets" / "contributors.svg"

BEGIN = "<!-- BEGIN contributors (generated by tools/contributors.py --write) -->"
END = "<!-- END contributors -->"
SITE = "https://zjunlp.github.io/HarnessGrad-Hub/contributors/"

BOARDS = ("harness", "method", "benchmark")
KIND_COLOURS = {
    "benchmark": "#2f6f8f",
    "method": "#8a5a9e",
    "harness": "#5c8a57",
    "platform": "#b08930",
    "result": "#a04a6b",
}
KIND_ORDER = ("harness", "method", "benchmark", "platform", "result")


# ------------------------------------------------------------------ the record ---

def declared_benchmarks() -> list[str]:
    return sorted(path.stem for path in (ROOT / "data" / "datasets").glob("*.py")
                  if path.stem != "__init__")


def record() -> dict:
    return json.loads(RECORD.read_text(encoding="utf-8"))


def entries(record: dict) -> list[dict]:
    """Every credited entry, with its kind attached."""
    out = []
    for board in BOARDS:
        for entry in record["boards"][board]:
            out.append({**entry, "kind": board})
    for entry in record.get("platform") or []:
        out.append({**entry, "kind": "platform"})
    for entry in (record.get("results") or {}).get("entries") or []:
        out.append({"name": f"{entry['benchmark']}·{entry['metric']}", "kind": "result",
                    "contributor": entry["contributor"], "since": entry.get("since", ""),
                    "note": f"{entry.get('method', '?')} on {entry.get('harness', '?')}"})
    return out


def problems(record: dict) -> list[str]:
    found: list[str] = []
    people = {person["handle"] for person in record.get("people") or []}
    if not people:
        found.append("no people are listed")
    credited = {entry["contributor"] for entry in entries(record)}
    for handle in sorted(credited - people):
        found.append(f"a credit names @{handle}, who is not in `people`")
    for handle in sorted(people - credited):
        found.append(f"@{handle} is listed with no credit")

    for board in BOARDS:
        listed = {entry["name"] for entry in record["boards"][board]}
        if board == "benchmark":
            missing = sorted(set(declared_benchmarks()) - listed)
            if missing:
                found.append(f"benchmark: declared but not credited: {missing}")
            extra = sorted(listed - set(declared_benchmarks()))
            if extra:
                found.append(f"benchmark: credited but not declared: {extra}")
    for entry in record.get("platform") or []:
        path = ROOT / entry["path"]
        if not path.exists():
            found.append(f"platform/{entry.get('name')}: path does not exist: {entry['path']}")
    for entry in entries(record):
        if not entry.get("since", "").startswith("20"):
            found.append(f"{entry['kind']}/{entry.get('name')}: no since month")
    for person in record.get("people") or []:
        if not person.get("handle") or not person.get("name"):
            found.append("a person has no handle or no name")
    return found


# ------------------------------------------------------------------ rendering ---

def months(items: list[dict]) -> list[str]:
    values = sorted({entry["since"][:7] for entry in items if entry.get("since")})
    if not values:
        return []
    first, last = values[0], values[-1]
    year, month = (int(part) for part in first.split("-"))
    out = []
    while True:
        current = f"{year:04d}-{month:02d}"
        out.append(current)
        if current == last:
            break
        month += 1
        if month == 13:
            year, month = year + 1, 1
    return out


def totals(items: list[dict]) -> list[tuple[str, int]]:
    counts = Counter(entry["contributor"] for entry in items)
    return sorted(counts.items(), key=lambda item: (-item[1], item[0].lower()))


def _kind_counts(items: list[dict]) -> Counter:
    return Counter(entry["kind"] for entry in items)


def render_svg(record: dict) -> str:
    """The graph: rows are people, columns are months, hover says what a cell holds."""
    people = record["people"]
    items = entries(record)
    columns = months(items)
    order = totals(items)
    ranks = {handle: index + 1 for index, (handle, _) in enumerate(order)}
    by_person = {person["handle"]: person for person in people}

    left, top = 190, 74
    cell_w, cell_h = 62, 48
    width = left + cell_w * max(len(columns), 1) + 196
    height = top + cell_h * len(order) + 74
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
             f'viewBox="0 0 {width} {height}" font-family="-apple-system,Segoe UI,Helvetica,Arial,'
             f'sans-serif" role="img" aria-label="Contribution graph by month">',
             f'<rect width="{width}" height="{height}" fill="#ffffff"/>']

    parts.append(f'<text x="24" y="28" font-size="13" font-weight="600" fill="#1f2328">'
                 f'Who contributed what, by month</text>')
    parts.append(f'<text x="24" y="44" font-size="11" fill="#6e7781">'
                 f'hover a square for the entries; {len(items)} credited in total</text>')

    for index, column in enumerate(columns):
        x = left + index * cell_w + cell_w / 2
        parts.append(f'<text x="{x:.0f}" y="{top - 12}" font-size="11" fill="#6e7781" '
                     f'text-anchor="middle">{column}</text>')

    for row, (handle, count) in enumerate(order):
        y = top + row * cell_h
        person = by_person.get(handle, {})
        parts.append(f'<circle cx="36" cy="{y + 18}" r="13" fill="{KIND_COLOURS["platform"]}" '
                     f'opacity="0.18"/>')
        parts.append(f'<text x="36" y="{y + 22}" font-size="12" text-anchor="middle" '
                     f'fill="#1f2328">{handle[:1].upper()}</text>')
        parts.append(f'<text x="58" y="{y + 16}" font-size="12" fill="#1f2328">{handle}</text>')
        parts.append(f'<text x="58" y="{y + 31}" font-size="10" fill="#6e7781">'
                     f'{(person.get("name") or "")[:30]}</text>')
        for index, column in enumerate(columns):
            selected = [entry for entry in items
                        if entry["contributor"] == handle and entry["since"][:7] == column]
            x = left + index * cell_w
            if not selected:
                parts.append(f'<rect x="{x + 4}" y="{y + 4}" width="{cell_w - 8}" '
                             f'height="{cell_h - 8}" rx="6" fill="#f4f5f7"/>')
                continue
            kinds = _kind_counts(selected)
            dominant = max(kinds, key=kinds.get)
            names = [entry["name"] for entry in selected]
            shown = ", ".join(names[:6]) + (f" and {len(names) - 6} more"
                                            if len(names) > 6 else "")
            tooltip = (f"{column} · @{handle} · {len(selected)} "
                       f"{'entry' if len(selected) == 1 else 'entries'}: {shown}")
            radius = min(4 + 3 * len(selected) ** 0.5, 21)
            parts.append(
                f'<g><title>{tooltip}</title>'
                f'<rect x="{x + 4}" y="{y + 4}" width="{cell_w - 8}" height="{cell_h - 8}" '
                f'rx="6" fill="{KIND_COLOURS[dominant]}" opacity="0.10"/>'
                f'<circle cx="{x + cell_w / 2:.0f}" cy="{y + cell_h / 2:.0f}" r="{radius:.0f}" '
                f'fill="{KIND_COLOURS[dominant]}" opacity="0.85"/>'
                f'<text x="{x + cell_w / 2:.0f}" y="{y + cell_h / 2 + 4:.0f}" font-size="10" '
                f'text-anchor="middle" fill="#ffffff">{len(selected)}</text></g>')
        right = left + cell_w * max(len(columns), 1) + 26
        parts.append(f'<text x="{right}" y="{y + 20}" font-size="13" font-weight="600" '
                     f'fill="#1f2328">{count}</text>')
        parts.append(f'<text x="{right}" y="{y + 34}" font-size="10" fill="#6e7781">'
                     f'#{ranks[handle]} of {len(order)}</text>')

    legend_y = top + cell_h * len(order) + 18
    x = 24
    parts.append(f'<text x="{x}" y="{legend_y}" font-size="10" fill="#6e7781">kind:</text>')
    x += 38
    for kind in KIND_ORDER:
        if kind not in {entry["kind"] for entry in items}:
            continue
        parts.append(f'<rect x="{x}" y="{legend_y - 8}" width="10" height="10" rx="2" '
                     f'fill="{KIND_COLOURS[kind]}" opacity="0.85"/>')
        parts.append(f'<text x="{x + 15}" y="{legend_y}" font-size="10" fill="#6e7781">'
                     f'{kind}</text>')
        x += 20 + 6 * len(kind)
    parts.append(f'<text x="24" y="{legend_y + 20}" font-size="10" fill="#6e7781">'
                 f'months are adoption months in this record; the website adds a date-range '
                 f'picker.</text>')
    parts.append("</svg>")
    return "\n".join(parts)


def render_block(record: dict) -> str:
    """The whole generated block: graph, totals, and the one board that stays a ranking."""
    items = entries(record)
    order = totals(items)
    rows = ["| # | contributor | contributed |", "| --- | --- | --- |"]
    for rank, (handle, count) in enumerate(order, start=1):
        rows.append(f"| {rank} | [@{handle}](https://github.com/{handle}) | "
                    f"[{count}]({DETAILS.relative_to(ROOT).as_posix()}#{handle.lower()}) |")
    body = "\n".join([
        f"![Who contributed what, by month]({FIGURE.relative_to(ROOT).as_posix()})",
        "",
        "One row per contributor, one column per month, and the number in a square is how many "
        "entries landed that month — hover it and it names them. The right-hand column repeats "
        "the total and the rank, so the ordering is stated rather than implied by position. "
        f"[Every entry, per person]({DETAILS.relative_to(ROOT).as_posix()}) is a list; "
        f"the [website]({SITE}) draws the same record with a date-range picker.",
        "",
        *rows,
    ])
    return "\n".join([BEGIN, body, "", *render_results(record), END])


def render_details(record: dict) -> str:
    lines = [
        "# Who contributed what",
        "",
        "Generated by `python3 tools/contributors.py --write` from "
        "[`registry/leaderboards.json`](../registry/leaderboards.json); do not edit by hand.",
        "",
        "Ordered by number of credited entries. `since` is the month an entry was adopted into "
        "the catalogue; the history was squashed for release, so that — not a file's first "
        "commit — is the honest date available.",
        "",
    ]
    items = entries(record)
    for handle, count in totals(items):
        person = next((p for p in record["people"] if p["handle"] == handle), {})
        lines.extend([f'<a id="{handle.lower()}"></a>', "",
                      f"## [@{handle}](https://github.com/{handle}) — {count} "
                      f"{'entry' if count == 1 else 'entries'}", ""])
        if person.get("name"):
            lines.append(f"{person['name']}. {person.get('note', '')}".strip())
            lines.append("")
        for kind in KIND_ORDER:
            selected = sorted((entry for entry in items
                               if entry["contributor"] == handle and entry["kind"] == kind),
                              key=lambda entry: (entry.get("since", ""), entry["name"]))
            if not selected:
                continue
            lines.append(f"**{kind}**")
            lines.append("")
            for entry in selected:
                note = entry.get("note") or ""
                lines.append(f"- `{entry['name']}` — {entry.get('since', '')}"
                             + (f" — {note}" if note else ""))
            lines.append("")
    return "\n".join(lines)


def render_results(record: dict) -> list[str]:
    """The measured-results table: the one board that stays a ranking, inside a group."""
    entries_ = (record.get("results") or {}).get("entries") or []
    lines = ["### Measured results", ""]
    if not entries_:
        lines.append("*No comparable result has been contributed yet. A result needs a "
                     "benchmark+metric group, a receipt in this repository, and the tree hash "
                     "the score was measured on — see [docs/leaderboards.md](docs/leaderboards.md).*")
        return lines
    groups: dict[tuple[str, str], list[dict]] = {}
    for entry in entries_:
        groups.setdefault((entry["benchmark"], entry["metric"]), []).append(entry)
    for (benchmark, metric), members in sorted(groups.items()):
        lines.extend([f"**{benchmark} · {metric}**", "",
                      "| # | score | method | harness | contributor | receipt |",
                      "| --- | --- | --- | --- | --- | --- |"])
        members.sort(key=lambda entry: -float(entry["score"]))
        for rank, entry in enumerate(members, start=1):
            handle = entry["contributor"]
            lines.append(f"| {rank} | {entry['score']} | `{entry.get('method', '?')}` | "
                         f"`{entry.get('harness', '?')}` | "
                         f"[@{handle}](https://github.com/{handle}) | "
                         f"[receipt]({entry['receipt']}) |")
        lines.append("")
    return lines


# ---------------------------------------------------------------------- files ---

def _block(text: str, begin: str, end: str) -> str | None:
    if begin not in text or end not in text:
        return None
    return text[text.index(begin):text.index(end) + len(end)]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not (args.write or args.check):
        parser.error("one of --write or --check is required")

    data = record()
    found = problems(data)
    if found:
        for line in found:
            print(f"error: {line}", file=sys.stderr)
        return 2

    block = render_block(data)
    svg = render_svg(data)
    details = render_details(data)

    if args.check:
        readme = README.read_text(encoding="utf-8")
        stale = []
        if _block(readme, BEGIN, END) != render_block(data):
            stale.append("the contributor block")
        if not FIGURE.is_file() or FIGURE.read_text(encoding="utf-8") != svg:
            stale.append(FIGURE.relative_to(ROOT).as_posix())
        if not DETAILS.is_file() or DETAILS.read_text(encoding="utf-8") != details:
            stale.append(DETAILS.relative_to(ROOT).as_posix())
        if stale:
            print("stale: " + ", ".join(stale) + "; run python3 tools/contributors.py --write",
                  file=sys.stderr)
            return 1
        print(f"contributors ok: {len(data['people'])} people, {len(entries(data))} entries, "
              f"{len(months(entries(data)))} months")
        return 0

    readme = README.read_text(encoding="utf-8")
    existing = _block(readme, BEGIN, END)
    if existing is None:
        raise SystemExit(f"error: the README has no block starting with {BEGIN!r}")
    README.write_text(readme.replace(existing, block), encoding="utf-8")
    FIGURE.parent.mkdir(parents=True, exist_ok=True)
    FIGURE.write_text(svg, encoding="utf-8")
    DETAILS.write_text(details, encoding="utf-8")
    print(f"wrote {FIGURE.relative_to(ROOT).as_posix()}, {DETAILS.relative_to(ROOT).as_posix()} "
          f"and the README block")
    return 0


if __name__ == "__main__":
    sys.exit(main())
