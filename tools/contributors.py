def _block(text: str, begin: str, end: str) -> str | None:
    if begin not in text or end not in text:
        return None
    return text[text.index(begin):text.index(end) + len(end)]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not (args.write or args.check):
        parser.error("one of --write or --check is required")

    data = record()
    found = problems(data)
    if found:
        for line in found:
            print(f"error: {line}", file=sys.stderr)
        return 2

    block = render_block(data)
    svgs = {board: render_svg(data, board) for board in FIGURES}
    details = render_details(data)
    page = render_html(data)

    if args.check:
        readme = REFERENCE.read_text(encoding="utf-8")
        stale = []
        if _block(readme, BEGIN, END) != render_block(data):
            stale.append("the contributor block")
        for board, path in FIGURES.items():
            if not path.is_file() or path.read_text(encoding="utf-8") != svgs[board]:
                stale.append(path.relative_to(ROOT).as_posix())
        if not DETAILS.is_file() or DETAILS.read_text(encoding="utf-8") != details:
            stale.append(DETAILS.relative_to(ROOT).as_posix())
        if not PAGE.is_file() or PAGE.read_text(encoding="utf-8") != page:
            stale.append(PAGE.relative_to(ROOT).as_posix())
        if stale:
            print("stale: " + ", ".join(stale) + "; run python3 tools/contributors.py --write",
                  file=sys.stderr)
            return 1
        print(f"contributors ok: {len(data['people'])} people, {len(entries(data))} entries, "
              f"{len(months(entries(data)))} months")
        return 0

    readme = REFERENCE.read_text(encoding="utf-8")
    existing = _block(readme, BEGIN, END)
    if existing is None:
        raise SystemExit(f"error: the reference page has no block starting with {BEGIN!r}")
    REFERENCE.write_text(readme.replace(existing, block), encoding="utf-8")
    for board, path in FIGURES.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(svgs[board], encoding="utf-8")
    DETAILS.write_text(details, encoding="utf-8")
    PAGE.write_text(page, encoding="utf-8")
    print("wrote " + ", ".join(path.relative_to(ROOT).as_posix() for path in FIGURES.values())
          + f", {DETAILS.relative_to(ROOT).as_posix()}, {PAGE.relative_to(ROOT).as_posix()} "
          f"and the reference contributor block")
    return 0


if __name__ == "__main__":
    sys.exit(main())
