"""The documentation graph must not link to files that are not there.

Root, docs and tracked data Markdown cross-reference source as directories, files
and pytest modules move. Two kinds of breakage are silent:

* a relative link `[text](docs/other.md)` whose target moved or was removed is a
  404 for every reader, but renders fine in the editor that wrote it;
* an inline `` `docs/other.md` `` that names a file which no longer exists is
  invisible until someone tries to open it -- there is nothing to click.

This test walks the same graph and asserts, for every relative link and every
inline path that claims to name a path *in this repository*, that the target
exists (case-exact: Linux is case-sensitive) and that a ``#anchor`` on it names a
heading in the target file. It is the mechanical form of the audit that produced
it; failures name the file, the line and the target.

**What is deliberately not checked, and why** -- each of these was a real
false-positive source while the rule was being written:

* **Generated files.** `DATASETS.md` and `DOWNLOADS.md` are rendered by
  `tools/datasets.py --write` and say so in a banner. A hand-edit here is lost on
  the next regeneration, so holding them to the rule would demand a fix the
  author cannot make. `DOWNLOADS.md` is also a checksum manifest whose `data/...`
  strings are download *destinations*, not tracked files.
* **Content and evidence roots.** `reports/` and `tests/fixtures/` may hold
  external receipts or frozen fixtures. Under `data/`, only dataset asset paths
  are exempt: scaffolding, adapter modules and other source targets are checked.
* **Absolute paths and placeholders.** `/tmp/...`, `/logs/...`, `a/{b,c}.json` and
  `x/.../y.py` are shapes, not targets.
* **Spans that are a record, not navigation.** A document may carry
  ``<!-- documentation-links: historical -->`` when its entries cite per-task
  artifacts and per-task test modules that were produced outside the checkout or
  removed when the suite was slimmed. `docs/adapter-integration-journal.md` is
  such a log: the names are the record and rewriting them would falsify it. Its
  *links* are still checked -- a link that 404s is never acceptable.
* **Spans the paragraph declares absent.** `` `docs/x.md` `` inside a paragraph
  that says the page "no longer exists" or "was deleted" is documenting a removal,
  not pointing at a file. The cue is read from the enclosing paragraph only.
* **Non-repository paths.** A span is a repository path only when its first
  segment is a tracked top-level entry. `` `lib/tau_bench/envs/hash.py` `` in the
  vendor notes describes an upstream package layout, not this tree.

Nothing here asserts a page *should* exist. A missing page that the prose
promises is a content defect: the fix is to write it or stop promising it, and
this test can only report the citation.
"""
from __future__ import annotations

import posixpath
import re
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]

#: Extensions a code span must end in to be read as a repository path.
PATH_SUFFIXES = (".md", ".json", ".py", ".sh", ".txt")

#: A public checkout holds none of these, so a path into them is not a claim.
CONTENT_ROOTS = ("reports/", "tests/fixtures/")


def _external_content(path: str) -> bool:
    """Only per-dataset asset directories may contain untracked payloads."""
    if path.startswith(CONTENT_ROOTS):
        return True
    parts = path.split("/")
    # Dataset assets may be external, but source/document links are repository
    # contracts and must never inherit a blanket asset-directory exemption.
    asset = (len(parts) >= 4 and parts[:2] == ["data", "datasets"]
             and not parts[2].endswith(".py") and Path(path).suffix not in ('.py', '.md', '.sh'))
    return asset or path == "data/candidates" or path.startswith("data/local_ignored_module/")


# Exact non-repository citations: an upstream source and a removed historical test.
NON_REPOSITORY_CITATIONS = {
    ("data/datasets/strongreject/README.md", "tests/test_outputs.py"),
    ("data/datasets/spreadsheetbench/w-spreadcache.md",
     "tests/quality/test_spreadsheetbench_classification_w_spread2.py"),
}

# These migration records describe the old data layout, not current paths.
LEGACY_DATA_DOCUMENTS = {
    "docs/data-layout-open-items.md", "docs/data-split-plan.md",
    "docs/registry-discovery-order.md", "docs/tau-bench-vendoring.md",
}

#: The banner `tools/datasets.py --write` puts at the top of a rendered file.
GENERATED = re.compile(r"generated by .*?do not edit", re.I | re.S)

#: Opt-out for documents that cite artifacts as a historical record.
HISTORICAL = "documentation-links: historical"

#: A paragraph that says the target is gone is documenting a removal.
ABSENCE = re.compile(
    r"no longer exists|deleted|removed|moved here from|historical|superseded|"
    r"withdrawn|is gone|was gone|absent|still a proposal|no longer present",
    re.I,
)

FENCE = re.compile(r"^( {0,3})(`{3,}|~{3,})(.*)$")
LINK = re.compile(r"(?<!!)\[([^\[\]]*)\]\(\s*([^()\s]*(?:\([^()]*\)[^()\s]*)*)\s*\)")
HTML_LINK = re.compile(r"""<a\s[^>]*\bhref=["']([^"']+)["']""", re.I)
SPAN = re.compile(r"(?<!`)(`+)(?!`)(.+?)(?<!`)\1(?!`)")
LINENO = re.compile(r"^(.*?\.(?:md|json|py|sh|txt)):(\d+)$")
SCHEME = re.compile(r"^[a-z][a-z0-9+.-]*:", re.I)
HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")


# --------------------------------------------------------------------------- #
# Repository facts, read once per session


def _tracked() -> list[str]:
    """Tracked paths, NUL-separated so a non-ASCII name is not quoted at us."""
    try:
        done = subprocess.run(
            ["git", "-C", str(ROOT), "ls-files", "-z"],
            capture_output=True, text=True, timeout=30,
        )
        if done.returncode == 0 and done.stdout:
            return [p for p in done.stdout.split("\0") if p]
    except (OSError, subprocess.SubprocessError):
        pass
    # No git (an extracted tarball): the documentation tree is what we can see.
    fallback = [p.name for p in ROOT.glob("*.md")]
    # In an export there is no index: treat visible files as the available tree.
    fallback += [str(p.relative_to(ROOT)) for p in ROOT.rglob("*") if p.is_file()]
    return sorted(set(fallback))


def _scope(tracked: list[str]) -> list[str]:
    """Tracked markdown at the root and under ``docs/`` or ``data/``."""
    keep = []
    for path in tracked:
        if not path.endswith(".md"):
            continue
        if "/" not in path:
            keep.append(path)
        elif path.startswith(("docs/", "data/")) and "/fixtures/" not in path:
            keep.append(path)
    return sorted(keep)


def _top_level() -> set[str]:
    """Directories this repository has at its top level, hidden ones excluded."""
    try:
        return {p.name for p in ROOT.iterdir() if p.is_dir() and not p.name.startswith(".")}
    except OSError:  # pragma: no cover - unreadable checkout
        return set()


def _slug(heading: str) -> str:
    """GitHub's anchor rule: lowercase, punctuation dropped, spaces to hyphens."""
    lowered = heading.strip().lower().replace("`", "")
    return re.sub(r"[^\w\- ]", "", lowered).replace(" ", "-")


#: An explicit anchor. A generated page groups rows by contributor and the heading carries a
#: count ("@zjunlp — 8 entries"), so the stable anchor is written rather than derived: a slug
#: that changes when the count changes is not an anchor a link can point at.
EXPLICIT_ANCHOR = re.compile(r'<a\s+id="([^"]+)"')


def _headings(path: Path) -> list[str] | None:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return None
    found: list[str] = []
    seen: dict[str, int] = {}
    fenced = False
    for line in lines:
        if FENCE.match(line):
            fenced = not fenced
            continue
        if fenced:
            continue
        for anchor in EXPLICIT_ANCHOR.finditer(line):
            found.append(anchor.group(1))
        match = HEADING.match(line)
        if not match:
            continue
        base = _slug(match.group(2))
        nth = seen.get(base, 0)
        seen[base] = nth + 1
        found.append(base if nth == 0 else f"{base}-{nth}")
    return found


def _paragraph(lines: list[str], lineno: int) -> str:
    """The blank-line-delimited paragraph around a 1-based line number."""
    start = lineno - 1
    while start > 0 and lines[start - 1].strip():
        start -= 1
    end = lineno
    while end < len(lines) and lines[end].strip():
        end += 1
    return " ".join(lines[start:end])


def _path_like(text: str) -> bool:
    if not text or "/" not in text or any(c in text for c in " \t*<>|=…»"):
        return False
    if SCHEME.match(text):
        return False
    return text.endswith(PATH_SUFFIXES) or text.endswith("/") or bool(LINENO.match(text))


def _placeholder(text: str) -> bool:
    return any(c in text.split("#", 1)[0] for c in "{}<>*")


def _is_repo_path(text: str, top: set[str]) -> bool:
    text = LINENO.sub(r"\1", text.strip())
    if not text or text.startswith(("/", "./", "../")):
        return False
    return text.split("/", 1)[0] in top


def _candidates(rel: str, target: str) -> list[str]:
    """Repo-relative and document-relative readings of one inline path."""
    bare = LINENO.sub(r"\1", target.strip()).rstrip("/")
    base = rel.rsplit("/", 1)[0] if "/" in rel else ""
    out = [posixpath.normpath(bare)]
    if base:
        out.append(posixpath.normpath(posixpath.join(base, bare)))
    return out


# --------------------------------------------------------------------------- #
# The single scan


class Finding:
    __slots__ = ("kind", "file", "line", "target", "detail", "resolved")

    def __init__(self, kind: str, file: str, line: int, target: str, detail: str,
                 resolved: str = "") -> None:
        self.kind, self.file, self.line = kind, file, line
        self.target, self.detail, self.resolved = target, detail, resolved

    def __str__(self) -> str:
        return f"{self.file}:{self.line}: {self.kind} {self.target!r} -> {self.detail}"


def _scan() -> dict[str, object]:
    tracked = _tracked()
    top = _top_level()
    tracked_set = set(tracked)
    tracked_dirs = {parent.as_posix() for p in tracked for parent in Path(p).parents if str(parent) != "."}

    def exists(rel: str, target: str) -> bool:
        if rel.startswith("data/"):
            return (target in tracked_set or target in tracked_dirs) and (ROOT / target).exists()
        return (ROOT / target).exists()

    documents = _scope(tracked)
    counts = {"documents": 0, "links": 0, "inline": 0, "anchors": 0, "external": 0}
    findings: list[Finding] = []
    skipped = {"generated": 0, "historical-inline": 0, "absent-citation": 0}

    for rel in documents:
        path = ROOT / rel
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except OSError:  # a tracked file deleted from the working tree
            findings.append(Finding("document", rel, 0, rel, "unreadable tracked markdown"))
            continue
        text = "\n".join(lines)
        if GENERATED.search(text[:600]):
            skipped["generated"] += 1
            continue
        counts["documents"] += 1
        historical = HISTORICAL in text
        base = rel.rsplit("/", 1)[0] if "/" in rel else ""
        own_headings = _headings(path) or []
        fenced = False

        for lineno, line in enumerate(lines, 1):
            if FENCE.match(line):
                fenced = not fenced
                continue
            if fenced:
                continue

            for match in LINK.finditer(line):
                target = match.group(2)
                if SCHEME.match(target):
                    counts["external"] += 1
                    continue
                if target.startswith("#"):
                    counts["anchors"] += 1
                    slug = target[1:]
                    if slug and slug not in own_headings:
                        findings.append(Finding(
                            "prose-anchor", rel, lineno, target,
                            f"no heading #{slug} in {rel}"))
                    continue
                counts["links"] += 1
                file_part, _, fragment = target.partition("#")
                file_part = file_part.split("?", 1)[0]
                if not file_part or _placeholder(target):
                    continue
                resolved = posixpath.normpath(
                    posixpath.join(base, file_part) if base else file_part)
                if _external_content(resolved):
                    continue
                if not exists(rel, resolved):
                    findings.append(Finding(
                        "link", rel, lineno, target, f"missing {resolved}", resolved))
                    continue
                if fragment:
                    counts["anchors"] += 1
                    target_path = ROOT / resolved
                    if target_path.is_dir():
                        target_path = target_path / "README.md"
                        resolved = f"{resolved}/README.md"
                    if target_path.suffix == ".md":
                        headings = _headings(target_path)
                        if headings is not None and fragment not in headings:
                            findings.append(Finding(
                                "link-anchor", rel, lineno, target,
                                f"no heading #{fragment} in {resolved}"))

            for match in HTML_LINK.finditer(line):
                target = match.group(1)
                if SCHEME.match(target) or target.startswith("#") or _placeholder(target):
                    continue
                file_part = target.split("#", 1)[0]
                if not file_part:
                    continue
                counts["links"] += 1
                resolved = posixpath.normpath(
                    posixpath.join(base, file_part) if base else file_part)
                if _external_content(resolved):
                    continue
                if not exists(rel, resolved):
                    findings.append(Finding(
                        "html-link", rel, lineno, target, f"missing {resolved}", resolved))

            if historical:
                continue
            paragraph = None
            for match in SPAN.finditer(line):
                span = match.group(2).strip()
                if not _path_like(span) or not _is_repo_path(span, top) or _placeholder(span):
                    continue
                counts["inline"] += 1
                if (rel, LINENO.sub(r"\1", span)) in NON_REPOSITORY_CITATIONS:
                    continue
                resolved = next(
                    (c for c in _candidates(rel, span) if exists(rel, c)),
                    _candidates(rel, span)[0],
                )
                if _external_content(resolved) or (rel in LEGACY_DATA_DOCUMENTS and resolved.startswith("data/")):
                    continue
                absolute = ROOT / resolved
                wants_directory = span.endswith("/")
                if not exists(rel, resolved):
                    if paragraph is None:
                        paragraph = _paragraph(lines, lineno)
                    if ABSENCE.search(paragraph):
                        skipped["absent-citation"] += 1
                    else:
                        findings.append(Finding(
                            "inline", rel, lineno, span, f"missing {resolved}", resolved))
                elif wants_directory and not absolute.is_dir():
                    findings.append(Finding(
                        "inline", rel, lineno, span,
                        f"{resolved} is a file, not a directory"))
                elif not wants_directory and absolute.is_dir():
                    findings.append(Finding(
                        "inline", rel, lineno, span,
                        f"{resolved} is a directory; the text says file"))

    return {"counts": counts, "findings": findings, "skipped": skipped}


_STATE: dict[str, object] = {}


def _result() -> dict[str, object]:
    if not _STATE:
        _STATE.update(_scan())
    return _STATE


def _of(kind: str) -> list[Finding]:
    return [f for f in _result()["findings"] if f.kind == kind]  # type: ignore[union-attr]


def _report(findings: list[Finding]) -> str:
    return f"{len(findings)} broken:\n" + "\n".join(f"  {f}" for f in findings)


# --------------------------------------------------------------------------- #
# The assertions


def test_the_documentation_graph_is_covered():
    """The scan has to look at the graph, not an empty list."""
    counts = _result()["counts"]
    assert counts["documents"] >= 40, counts
    # Historical operational journal was archived; count the remaining live graph.
    assert counts["links"] >= 220, counts
    assert counts["inline"] >= 300, counts


@pytest.mark.parametrize("path, exempt", [
    ("data/scaffolds/missing.py", False),
    ("data/datasets/missing.py", False),
    ("data/datasets/gaia/private.json", True),
    ("data/datasets/gaia/missing.py", False),
    ("data/datasets/gaia/missing.md", False),
    ("data/dataset.schema.json", False),
    ("reports/receipt.json", True),
])
def test_content_exemptions_are_narrow(path, exempt):
    assert _external_content(path) is exempt


def test_data_document_scan_uses_tracked_targets_offline(tmp_path, monkeypatch):
    document = tmp_path / "data/datasets/example/README.md"
    document.parent.mkdir(parents=True)
    document.write_text(
        "# Example\n"
        "[good](source.py) [missing](missing.py) [untracked](untracked.py)\n"
        "<a href=\"untracked.py\">untracked</a>\n"
        "`data/datasets/example/source.py` `data/datasets/example/untracked.py`\n"
        "[asset](payload.json) [external](https://invalid.example/file)\n",
        encoding="utf-8",
    )
    for name in ("source.py", "untracked.py"):
        (document.parent / name).write_text("", encoding="utf-8")
    tracked = ["data/datasets/example/README.md", "data/datasets/example/source.py"]
    monkeypatch.setattr(__import__(__name__), "ROOT", tmp_path)
    monkeypatch.setattr(__import__(__name__), "_tracked", lambda: tracked)
    result = _scan()
    findings = result["findings"]
    assert {(f.kind, f.target) for f in findings} == {
        ("link", "missing.py"), ("link", "untracked.py"),
        ("html-link", "untracked.py"),
        ("inline", "data/datasets/example/untracked.py"),
    }
    assert result["counts"]["external"] == 1


def test_data_scope_excludes_fixtures():
    assert _scope(["data/a/README.md", "data/a/fixtures/sample.md", "data/a/code.py"]) == [
        "data/a/README.md"
    ]


def test_relative_links_resolve():
    findings = _of("link") + _of("html-link")
    assert not findings, _report(findings)


def test_link_anchors_resolve():
    findings = _of("link-anchor")
    assert not findings, _report(findings)


def test_inline_repository_paths_exist():
    findings = _of("inline")
    assert not findings, _report(findings)


def test_prose_anchors_resolve():
    findings = _of("prose-anchor")
    assert not findings, _report(findings)


def test_external_urls_are_not_fetched():
    """Every URL scheme is skipped; the audit is about links inside the repo."""
    counts = _result()["counts"]
    assert counts["external"] >= 1
    assert not [f for f in _result()["findings"] if "://" in f.target]  # type: ignore[union-attr]


@pytest.mark.parametrize("kind", ["link", "inline", "link-anchor", "prose-anchor"])
def test_failures_name_file_line_and_target(kind):
    """Every failure a reader could get has to be locatable."""
    for finding in _of(kind):
        assert finding.file and finding.line >= 1 and finding.target, finding
